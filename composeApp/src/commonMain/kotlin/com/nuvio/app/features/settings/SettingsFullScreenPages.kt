@Composable
fun HomescreenSettingsScreen(
    onBack: () -> Unit,
) {
    val pluginsUiState by PluginRepository.uiState.collectAsStateWithLifecycle()
    val pluginsLoading = pluginsUiState.repositories.any { it.isRefreshing }
    val pluginErrorMessage = pluginsUiState.repositories.firstNotNullOfOrNull { it.errorMessage }
    val homescreenSettingsUiState by remember {
        HomeCatalogSettingsRepository.snapshot()
        HomeCatalogSettingsRepository.uiState
    }.collectAsStateWithLifecycle()
    val collections by CollectionRepository.collections.collectAsStateWithLifecycle()

    LaunchedEffect(Unit) {
        PluginRepository.initialize()
        CollectionRepository.initialize()
    }

    LaunchedEffect(collections) {
        HomeCatalogSettingsRepository.syncCollections(collections)
    }

    NuvioScreen(
        modifier = Modifier.fillMaxSize(),
    ) {
        stickyHeader {
            NuvioScreenHeader(
                title = stringResource(Res.string.compose_settings_page_homescreen),
                onBack = onBack,
            )
        }
        homescreenSettingsContent(
            isTablet = false,
            heroEnabled = homescreenSettingsUiState.heroEnabled,
            showCatalogType = homescreenSettingsUiState.showCatalogType,
            hideUnreleasedContent = homescreenSettingsUiState.hideUnreleasedContent,
            items = homescreenSettingsUiState.items,
            isCatalogLoading = pluginsLoading,
            catalogErrorMessage = pluginErrorMessage,
        )
    }
}

